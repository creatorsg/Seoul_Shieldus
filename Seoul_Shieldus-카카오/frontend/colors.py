"""
점수(0~100)를 안전도 색상으로 바꾸는 단일 기준점.

사이드바 점수 막대, 자치구 랭킹 표, (필요하면 나중에 다른 화면까지) 점수를 색으로
표현하는 모든 곳이 이 함수 하나만 같이 쓴다. 색 기준이나 임계값을 바꿔야 하면 여기 한 곳만 고치면 된다.
"""

# 점수 구간별 색. 낮은 점수(위험)일수록 빨강, 높은 점수(안전)일수록 초록.
# 지도 히트맵(RdYlGn)과 같은 계열로 맞춰서, 지도 색과 사이드바/표의 색이 서로 다른 뜻으로 안 읽히게 한다.
SCORE_COLOR_BANDS = [
    (40, "#EF4444"),   # 40점 미만: 위험 (빨강)
    (60, "#F57C00"),   # 40~60점: 주의 (주황)
    (75, "#F59E0B"),   # 60~75점: 보통 (황색)
    (101, "#22C55E"),  # 75점 이상: 안전 (초록)
]


def score_to_color(score: float) -> str:
    """0~100 점수를 안전도 색상(hex)으로 변환한다."""
    for threshold, color in SCORE_COLOR_BANDS:
        if score < threshold:
            return color
    return SCORE_COLOR_BANDS[-1][1]
